// No tracked file outside the fixture and static-asset directories exceeds 200 KB. Screenshots
// and generated reports are evidence for one PR, not part of what builds, tests or runs Mycel;
// committed, they made every clone of this public repository 13 MB heavier. Evidence belongs in
// the PR conversation or the CI artifacts. Run by `npm run lint:infra`, offline.
// Rejected: Git LFS (a second storage service for files nobody needs after review) and a total
// repository budget (one large file hides behind many small ones and the failure names nothing).

import { statSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'node:test';
import assert from 'node:assert/strict';

export const LIMIT = 200 * 1024;

/** Paths whose files may be large: test inputs, served static assets, the generated lockfile. */
const exempt = [
  /(^|\/)node_modules\//,
  /^packages\/[^/]+\/fixtures\//,
  /^scripts\/fixtures\//,
  /^apps\/web\/static\//,
  // Generated by npm and reviewed as a diff, never by size; splitting it is not an option.
  /^package-lock\.json$/,
];

/** The tracked paths over the limit, given `{ path, size }` entries. */
export function oversized(entries, limit = LIMIT) {
  return entries
    .filter(({ path, size }) => size > limit && !exempt.some((rule) => rule.test(path)))
    .map(({ path, size }) => `${path} (${Math.round(size / 1024)} KB)`);
}

const root = fileURLToPath(new URL('..', import.meta.url));

function tracked() {
  return execFileSync('git', ['ls-files', '-z'], { cwd: root, encoding: 'utf8' })
    .split('\0')
    .filter(Boolean)
    .flatMap((path) => {
      try {
        const stat = statSync(join(root, path));
        return stat.isFile() ? [{ path, size: stat.size }] : [];
      } catch {
        return []; // Deleted in the working tree but not yet staged.
      }
    });
}

test('no tracked file outside fixtures and static assets exceeds 200 KB', () => {
  assert.deepEqual(oversized(tracked()), []);
});

test('the size rule flags a screenshot and exempts fixtures, static assets and the lockfile', () => {
  const big = LIMIT + 1;
  assert.deepEqual(
    oversized([
      { path: 'docs/reports/editor-320.png', size: big },
      { path: 'docs/reports/small.png', size: LIMIT },
      { path: 'packages/db/fixtures/dump.sql', size: big },
      { path: 'scripts/fixtures/history.json', size: big },
      { path: 'apps/web/static/fonts/inter.woff2', size: big },
      { path: 'package-lock.json', size: big },
      { path: 'apps/web/fixtures/large.json', size: big },
    ]),
    ['docs/reports/editor-320.png (200 KB)', 'apps/web/fixtures/large.json (200 KB)']
  );
});
